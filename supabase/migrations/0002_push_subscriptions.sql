-- FUCIABOL — tabella per le sottoscrizioni alle notifiche push.
-- Da eseguire UNA VOLTA nell'SQL Editor di Supabase, dopo la 0001.

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  giocatore_id bigint not null,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;

drop policy if exists "anon full access" on public.push_subscriptions;
create policy "anon full access" on public.push_subscriptions
  for all to anon using (true) with check (true);
